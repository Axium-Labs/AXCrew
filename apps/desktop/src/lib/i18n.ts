export const dictionaries: Record<Lang, Record<string, string>> = { zh, en }

export type LangState = { lang: Lang; setLang: (lang: Lang) => void; toggleLang: () => void }

export const useLang = create<LangState>()(
  persist(
    set => ({
      lang: 'en',
      setLang: lang => set({ lang }),
      toggleLang: () => set(state => ({ lang: state.lang === 'zh' ? 'en' : 'zh' })),
    }),
    { name: 'ax-crew-language' },
  ),
)

/** True when English is active; handy for `cond ? 'x' : 'y'` copy without a second key. */
export function isEnglish() {
  return useLang.getState().lang === 'en'
}
function interpolate(text: string, vars?: Record<string, string | number>) {
  if (!vars) return text
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match))
}

/**
 * Translation for non-component callers. Components subscribe through `useT` or `useLang` so they
 * re-render when the language changes.
 */
export function translate(key: string, vars?: Record<string, string | number>) {
  const lang = useLang.getState().lang
  const text = dictionaries[lang][key] ?? dictionaries.zh[key]
  return text === undefined ? key : interpolate(text, vars)
}

export type TFn = (key: string, vars?: Record<string, string | number>) => string

/**
 * Subscribes to the language store, so every `t()` caller re-renders on toggle.
 * The identity is stable per language, which lets callers put `t` in `useMemo` deps.
 */
export function useT(): TFn {
  const lang = useLang(state => state.lang)
  return useCallback<TFn>((key, vars) => {
    const text = dictionaries[lang][key] ?? dictionaries.zh[key]
    return text === undefined ? key : interpolate(text, vars)
  }, [lang])
}
